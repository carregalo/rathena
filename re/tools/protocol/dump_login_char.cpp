// Prints, as JSON, the login and character server packets used by the client (src/common/packets.hpp) for this
// build's PACKETVER. Output: re/spec/protocol/login_char.json (see build.bat).
#include <common/cbasetypes.hpp>
#include <common/mmo.hpp>
#include <common/packets.hpp>

#include "dump_common.hpp"

int main(){
	std::printf("{\n  \"packetver\": %d,\n  \"structs\": {", PACKETVER);

	// login server
	STRUCT_BEGIN(PACKET_CA_LOGIN); FIELD(PACKET_CA_LOGIN, version); FIELD(PACKET_CA_LOGIN, username);
	FIELD(PACKET_CA_LOGIN, password); FIELD(PACKET_CA_LOGIN, clienttype); STRUCT_END();
	STRUCT_BEGIN(PACKET_AC_ACCEPT_LOGIN); FIELD(PACKET_AC_ACCEPT_LOGIN, packetLength); FIELD(PACKET_AC_ACCEPT_LOGIN, login_id1);
	FIELD(PACKET_AC_ACCEPT_LOGIN, AID); FIELD(PACKET_AC_ACCEPT_LOGIN, login_id2); FIELD(PACKET_AC_ACCEPT_LOGIN, sex);
	FIELD(PACKET_AC_ACCEPT_LOGIN, char_servers); STRUCT_END();
	STRUCT_BEGIN(PACKET_AC_ACCEPT_LOGIN_sub); FIELD(PACKET_AC_ACCEPT_LOGIN_sub, ip); FIELD(PACKET_AC_ACCEPT_LOGIN_sub, port);
	FIELD(PACKET_AC_ACCEPT_LOGIN_sub, name); FIELD(PACKET_AC_ACCEPT_LOGIN_sub, users); STRUCT_END();
	STRUCT_BEGIN(PACKET_AC_REFUSE_LOGIN); FIELD(PACKET_AC_REFUSE_LOGIN, error); STRUCT_END();

	// character server (CH_ENTER, 0x0065, has no struct: chclif_parse_reqtoconnect in src/char/char_clif.cpp
	// reads account id @2, login ids @6 and @10, sex @16, length 17)
	STRUCT_BEGIN(PACKET_HC_ACCEPT_ENTER); FIELD(PACKET_HC_ACCEPT_ENTER, packetLength); FIELD(PACKET_HC_ACCEPT_ENTER, characters); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_ACCEPT_ENTER2); FIELD(PACKET_HC_ACCEPT_ENTER2, packetLength); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_CHARLIST_NOTIFY); FIELD(PACKET_HC_CHARLIST_NOTIFY, total); STRUCT_END();
	STRUCT_BEGIN(PACKET_CH_CHARLIST_REQ); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_ACK_CHARINFO_PER_PAGE); FIELD(PACKET_HC_ACK_CHARINFO_PER_PAGE, packetLength);
	FIELD(PACKET_HC_ACK_CHARINFO_PER_PAGE, characters); STRUCT_END();
	STRUCT_BEGIN(CHARACTER_INFO); FIELD(CHARACTER_INFO, GID); FIELD(CHARACTER_INFO, speed); FIELD(CHARACTER_INFO, job);
	FIELD(CHARACTER_INFO, level); FIELD(CHARACTER_INFO, name); FIELD(CHARACTER_INFO, CharNum); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_BLOCK_CHARACTER); FIELD(PACKET_HC_BLOCK_CHARACTER, packetLength); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_SECOND_PASSWD_LOGIN); FIELD(PACKET_HC_SECOND_PASSWD_LOGIN, seed);
	FIELD(PACKET_HC_SECOND_PASSWD_LOGIN, AID); FIELD(PACKET_HC_SECOND_PASSWD_LOGIN, result); STRUCT_END();
	STRUCT_BEGIN(PACKET_CH_MAKE_CHAR); FIELD(PACKET_CH_MAKE_CHAR, name); FIELD(PACKET_CH_MAKE_CHAR, slot);
	FIELD(PACKET_CH_MAKE_CHAR, hair_color); FIELD(PACKET_CH_MAKE_CHAR, hair_style); FIELD(PACKET_CH_MAKE_CHAR, job);
	FIELD(PACKET_CH_MAKE_CHAR, sex); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_ACCEPT_MAKECHAR); FIELD(PACKET_HC_ACCEPT_MAKECHAR, character); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_REFUSE_MAKECHAR); FIELD(PACKET_HC_REFUSE_MAKECHAR, error); STRUCT_END();
	STRUCT_BEGIN(PACKET_CH_SELECT_CHAR); FIELD(PACKET_CH_SELECT_CHAR, slot); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_NOTIFY_ZONESVR); FIELD(PACKET_HC_NOTIFY_ZONESVR, CID); FIELD(PACKET_HC_NOTIFY_ZONESVR, mapname);
	FIELD(PACKET_HC_NOTIFY_ZONESVR, ip); FIELD(PACKET_HC_NOTIFY_ZONESVR, port); STRUCT_END();
	STRUCT_BEGIN(PACKET_HC_REFUSE_ENTER); FIELD(PACKET_HC_REFUSE_ENTER, error); STRUCT_END();

	std::printf("\n  }\n}\n");
	return 0;
}
