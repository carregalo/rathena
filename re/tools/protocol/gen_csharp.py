"""Writes client/RoNet/PacketLengths.g.cs from re/spec/protocol/lengths.json: the length of every packet the
servers send (-1 = variable, uint16 length at offset 2), so the client can split the byte stream.

Run after gen_lengths.py:  python gen_csharp.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.normpath(os.path.join(HERE, "..", "..", "spec", "protocol", "lengths.json"))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "client", "RoNet", "PacketLengths.g.cs"))


def table(name, lengths):
    rows = "\n".join(f"            {{ 0x{int(pid, 16):04x}, {length} }}," for pid, length in sorted(
        lengths.items(), key=lambda kv: int(kv[0], 16)) if length != 0)
    return f"        public static readonly Dictionary<ushort, short> {name} = new Dictionary<ushort, short>\n" \
           f"        {{\n{rows}\n        }};\n"


def main():
    spec = json.load(open(SPEC))
    code = f"""// Generated by re/tools/protocol/gen_csharp.py from re/spec/protocol/lengths.json. Do not edit.
// PACKETVER {spec['packetver']}. -1 = variable length (uint16 total length at offset 2).
using System.Collections.Generic;

namespace RoNet
{{
    public static class PacketLengths
    {{
        /// <summary>Packets sent by the login and character servers.</summary>
{table("LoginChar", spec["char"])}
        /// <summary>Packets sent by the map server.</summary>
{table("Map", spec["map"])}    }}
}}
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    print(f"wrote {OUT}: {len(spec['char'])} login/char, {len(spec['map'])} map packets")


if __name__ == "__main__":
    main()
